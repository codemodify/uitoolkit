//go:build ignore

// gen.go writes style/emojidata.go from the Unicode Character Database.
//
//	go run tools/emoji/gen.go                 # fetch the current emoji-data.txt
//	go run tools/emoji/gen.go path/to/file    # or read one already here
//
// Two properties, because the marking needs both and they are not the
// same question (UTS #51):
//
//   - Emoji_Presentation is "a picture with nobody asking". ⚡, ⭐ and ⌚
//     are in it; ❤ and 🏳 are not, and ask with U+FE0F.
//   - Extended_Pictographic is "could be part of a picture", which is
//     what a zero-width joiner needs to know about its neighbours: 🏳‍🌈
//     is a flag and a rainbow, neither of which carries a selector, and
//     the flag is not emoji by default.
//
// The range test this replaced — U+1F000 to U+1FAFF — was wrong in both
// directions, and two applications found it the same day: ⚡ came out a
// black outline where the table says picture, and 🜁, 🨀 and 🄰 came out
// pictures (then boxes, swallowed by the emoji run beside them) where
// the table says text.
package main

import (
	"bufio"
	"fmt"
	"io"
	"log"
	"net/http"
	"os"
	"sort"
	"strconv"
	"strings"
)

const source = "https://www.unicode.org/Public/UCD/latest/ucd/emoji/emoji-data.txt"

type span struct{ lo, hi rune }

func main() {
	log.SetFlags(0)
	log.SetPrefix("gen: ")

	var in io.ReadCloser
	from := source
	if len(os.Args) > 1 {
		from = os.Args[1]
		f, err := os.Open(from)
		if err != nil {
			log.Fatal(err)
		}
		in = f
	} else {
		resp, err := http.Get(source)
		if err != nil {
			log.Fatal(err)
		}
		if resp.StatusCode != http.StatusOK {
			log.Fatalf("%s: %s", source, resp.Status)
		}
		in = resp.Body
	}
	defer in.Close()

	want := map[string][]span{"Emoji_Presentation": nil, "Extended_Pictographic": nil}
	var version, date string
	sc := bufio.NewScanner(in)
	for sc.Scan() {
		line := sc.Text()
		if strings.HasPrefix(line, "#") {
			if v, ok := strings.CutPrefix(line, "# Version: "); ok {
				version = strings.TrimSpace(v)
			}
			if d, ok := strings.CutPrefix(line, "# Date: "); ok {
				date = strings.TrimSpace(d)
			}
			continue
		}
		if i := strings.IndexByte(line, '#'); i >= 0 {
			line = line[:i]
		}
		field := strings.Split(line, ";")
		if len(field) != 2 {
			continue
		}
		prop := strings.TrimSpace(field[1])
		if _, ok := want[prop]; !ok {
			continue
		}
		lo, hi, err := parseRange(strings.TrimSpace(field[0]))
		if err != nil {
			log.Fatalf("%s: %v", line, err)
		}
		want[prop] = append(want[prop], span{lo, hi})
	}
	if err := sc.Err(); err != nil {
		log.Fatal(err)
	}
	if version == "" {
		log.Fatal("no version line in the data; refusing to write a table nobody can date")
	}

	var b strings.Builder
	fmt.Fprintf(&b, `//go:build font_complex || font_emoji

package style

// Code generated by tools/emoji/gen.go. DO NOT EDIT.
//
// From the Unicode Character Database's emoji-data.txt, version %s
// (%%s), at
// %s
//
// Only the two properties the marking asks about are here; see
// [emojiPresentation] for what each one answers and why one range
// could not.
`, version, source)

	names := make([]string, 0, len(want))
	for p := range want {
		names = append(names, p)
	}
	sort.Strings(names)
	for _, p := range names {
		spans := merge(want[p])
		n := 0
		for _, s := range spans {
			n += int(s.hi-s.lo) + 1
		}
		fmt.Fprintf(&b, "\n// %s: %d ranges, %d code points.\nvar %s = [...]struct{ lo, hi rune }{\n",
			p, len(spans), n, varName(p))
		for _, s := range spans {
			if s.lo == s.hi {
				fmt.Fprintf(&b, "\t{0x%04X, 0x%04X},\n", s.lo, s.hi)
			} else {
				fmt.Fprintf(&b, "\t{0x%04X, 0x%04X},\n", s.lo, s.hi)
			}
		}
		b.WriteString("}\n")
	}

	out := fmt.Sprintf(b.String(), date)
	if err := os.WriteFile("style/emojidata.go", []byte(out), 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("style/emojidata.go: emoji-data.txt %s (%s), from %s\n", version, date, from)
}

func varName(prop string) string {
	switch prop {
	case "Emoji_Presentation":
		return "emojiPresentationRanges"
	case "Extended_Pictographic":
		return "extendedPictographicRanges"
	}
	panic(prop)
}

func parseRange(s string) (rune, rune, error) {
	lo, hi, found := strings.Cut(s, "..")
	if !found {
		hi = lo
	}
	a, err := strconv.ParseUint(lo, 16, 32)
	if err != nil {
		return 0, 0, err
	}
	z, err := strconv.ParseUint(hi, 16, 32)
	if err != nil {
		return 0, 0, err
	}
	return rune(a), rune(z), nil
}

// merge sorts the spans and joins the ones that touch, so that the
// table is searchable and as short as the data allows.
func merge(in []span) []span {
	if len(in) == 0 {
		return nil
	}
	sort.Slice(in, func(i, j int) bool { return in[i].lo < in[j].lo })
	out := []span{in[0]}
	for _, s := range in[1:] {
		last := &out[len(out)-1]
		if s.lo <= last.hi+1 {
			if s.hi > last.hi {
				last.hi = s.hi
			}
			continue
		}
		out = append(out, s)
	}
	return out
}
