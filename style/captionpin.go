// The keep-above pin.
//
// This is not a shape anyone here drew: it is a pushpin icon, traced from
// the artwork and kept. Every hand-drawn attempt at this glyph — a
// ceiling with a window under it, a tack of bars and needles, a pin put
// together from a profile swept along an axis — read as a smudge at the
// size a caption button is. So the outline is the artwork's own.
//
// How it was made: the icon was thresholded to a mask, its four pieces
// (handle, body, flange, needle) taken as separate shapes, the needle
// alone dilated to weigh a little more, and each piece reduced to its
// convex hull. Every piece is at least 97.8% of its own hull, so the
// hulls are the shapes and not an approximation of them — and a hull is
// a handful of points rather than a traced curve of hundreds.
//
// The coordinates are the unit square, y down, so the pin scales to any
// size by multiplication and nothing here is tied to a pixel grid.

